"""Regenerates the test inventory tables from tests/catalog.json (classification), docs/quality/test-timings-baseline.json (last measured cost)
and the test sources (static counts). Usage, from the repository root:

    python tools/quality/test_inventory.py                 # prints totals and writes docs/claude/test-inventory.md
    python tools/quality/test_inventory.py --check         # only validates the catalog against tests/*.gd (exit 1 on a problem)

Counts here are STATIC: a `check(` call site inside a loop executes many times, so site counts describe the source, not the number of
assertions executed in a run. A test script is one Godot process; it is the unit the runner selects.
"""
import json, os, re, sys
from collections import Counter

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
os.chdir(ROOT)
catalog = json.load(open('tests/catalog.json', encoding='utf-8'))
tests = catalog['tests']
names = sorted(f[:-3] for f in os.listdir('tests') if f.endswith('.gd'))
baseline = {}
if os.path.exists('docs/quality/test-timings-baseline.json'):
    baseline = json.load(open('docs/quality/test-timings-baseline.json', encoding='utf-8'))['tests']

problems = [n for n in names if n not in tests] + [n for n in tests if n not in names]
if '--check' in sys.argv:
    print('catalog problems:', problems or 'none')
    sys.exit(1 if problems else 0)

class_names = {}
for d, _, fs in os.walk('.'):
    if any(x in d for x in ('.godot', 'addons', '.git', 'artifacts')) or d.replace('\\', '/').startswith('./tests'):
        continue
    for f in fs:
        if f.endswith('.gd'):
            m = re.search(r'^class_name\s+(\w+)', open(os.path.join(d, f), encoding='utf-8', errors='ignore').read(), re.M)
            if m:
                class_names[m.group(1)] = os.path.join(d, f).replace('\\', '/')[2:]

rows = []
for n in names:
    text = open('tests/%s.gd' % n, encoding='utf-8', errors='ignore').read()
    sites = len(re.findall(r'\bcheck\w*\(|\bassert\w*\(|\bexpect\w*\(', text))
    private = len(set(re.findall(r'\b(?:adapter|rig|bench|actor|unit|modifier|crouch|visual|level|controller|service)\w*\.(_\w+)', text)))
    deps = set(re.findall(r'res://((?:systems|units|presentation|ui|levels|art|content|tools)/[\w/\.\-]+\.(?:gd|tscn))', text))
    used = sorted(c for c in class_names if re.search(r'\b%s\b' % c, text))
    e = tests.get(n, {})
    rows.append(dict(name=n, sub=e.get('sub', []), scope=e.get('scope', '?'), crit=e.get('crit') == 'critical', smoke=e.get('smoke', False),
                     fast=e.get('fast', False), explicit=e.get('run') == 'explicit', req=e.get('req', 'headless'), kind=e.get('kind', ''),
                     secs=baseline.get(n), sites=sites, private=private, deps=len(deps) + len(used), top=(sorted(deps)[:2] + used[:2])[:3],
                     contracts=e.get('contracts', [])))

def total(sel):
    return sum(r['secs'] or 0 for r in sel)

out = []
out.append('# Test inventory (generated)\n')
out.append('Generated by `tools/quality/test_inventory.py` from `tests/catalog.json`, `docs/quality/test-timings-baseline.json` and the test sources. Do not edit by hand.')
out.append('Static counts: "check sites" are `check(`/`assert`/`expect` call sites in the source (a site inside a loop runs many times), "private" counts distinct private members (`._name`) of production objects the script touches, "deps" counts referenced production scripts/scenes/classes. Time is the last measured cost (previous runner, 1 s granularity) and is `-` where never measured (explicit-only).\n')
out.append('## Totals\n')
out.append('| Quantity | Count |\n| --- | ---: |')
out.append('| Test scripts discovered (`tests/*.gd`) | %d |' % len(rows))
out.append('| Catalog entries | %d |' % len(tests))
out.append('| Explicit-only | %d (%d captures needing rendering, %d headless batches/benchmarks) |' % (sum(r['explicit'] for r in rows), sum(r['explicit'] and r['req'] == 'render' for r in rows), sum(r['explicit'] and r['req'] != 'render' for r in rows)))
out.append('| Ordinary (full tier) | %d |' % sum(not r['explicit'] for r in rows))
out.append('| FAST | %d |' % sum(r['fast'] for r in rows))
out.append('| SMOKE | %d |' % sum(r['smoke'] for r in rows))
out.append('| Critical | %d |' % sum(r['crit'] for r in rows))
out.append('| Static assertion call sites | %d |' % sum(r['sites'] for r in rows))
out.append('| Scripts touching production private members | %d |' % sum(r['private'] > 0 for r in rows))
out.append('')
out.append('## By scope\n')
out.append('| Scope | Scripts | Measured seconds |\n| --- | ---: | ---: |')
for s in ['unit', 'component', 'integration', 'battle', 'e2e']:
    sel = [r for r in rows if r['scope'] == s]
    out.append('| %s | %d | %.0f |' % (s, len(sel), total(sel)))
out.append('')
out.append('## By subsystem (a script can appear in several)\n')
out.append('| Subsystem | Scripts | Critical | FAST | Explicit-only | Measured seconds (ordinary) |\n| --- | ---: | ---: | ---: | ---: | ---: |')
c = Counter(s for r in rows for s in r['sub'])
for s, cnt in sorted(c.items(), key=lambda x: -x[1]):
    sel = [r for r in rows if s in r['sub']]
    out.append('| %s | %d | %d | %d | %d | %.0f |' % (s, cnt, sum(r['crit'] for r in sel), sum(r['fast'] for r in sel), sum(r['explicit'] for r in sel), total([r for r in sel if not r['explicit']])))
out.append('')
out.append('## Every test script\n')
out.append('| Test | Subsystems | Scope | Flags | Last measured (s) | Check sites | Private | Deps |\n| --- | --- | --- | --- | ---: | ---: | ---: | ---: |')
for r in rows:
    flags = [x for x, on in (('critical', r['crit']), ('smoke', r['smoke']), ('fast', r['fast']), ('explicit:' + r['kind'], r['explicit']), ('needs-render', r['req'] != 'headless')) if on]
    out.append('| `%s` | %s | %s | %s | %s | %d | %d | %d |' % (r['name'], ', '.join(r['sub']), r['scope'], ', '.join(flags) or '-', '%.1f' % r['secs'] if r['secs'] is not None else '-', r['sites'], r['private'], r['deps']))
target = 'docs/claude/test-inventory-2026-11-20.md'
open(target, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('wrote', target, '; problems:', problems or 'none')
for line in out[4:30]:
    print(line)
